# =============== Basic types ===================

# integer - any number
print(98)

# max integer
print(1e308)

# inf
print(1e309) # inf

# float - decimal number
print(9.3)

# max float
print(1.7e308)

# inf
print(1.7e309)

# boolean
print(True)
print(False)

# complex - imaginary number
print(4+5j)

# string 
print('Apple')
print("Apple2")
print("""Apple2""")

# ============== Container type ==================

# list
print([1, 2, 3, 4])

# tuple
print((1, 2, 3, 4))

# sets
print({1, 2, 3, 4, 5})

# dictionary 
print({"Name":"Kushagra", "Age":21, "gender":"Male"})
